/* Settles the long profile of the standard valley. Run after changing the model's physics or the valley:  node tools/river-calibrate.js [years]
   It runs a natural version of the valley (cut-down reaches given natural channels) with only the bed processes on, for a few
   centuries, until each stream has the slope that carries exactly the gravel it is given, then writes how far every node's bed
   moved to src/river-calib.js. The game applies those changes at the start, so streams that are healthy stay put. */
'use strict';
const { R } = require('./river-test.js');
const fs = require('fs'), path = require('path');
const YEARS = +process.argv[2] || 300;
const valley = R.buildValley({ seed: 11 });
const keyOf = (n) => n.reach.id + ':' + n.reach.nodes.indexOf(n);
R.CALIB = null;
const t0 = Date.now();
const m = new R.Model(valley, { seed: 5, natural: true, params: { bedOnly: true }, noCalib: true });
const bed0 = new Map(m.nodes.map((n) => [n.id, n.bed]));
for (let y = 0; y < YEARS; y++) {
  m.stepYear();
  if ((y + 1) % 50 === 0) { let s = 0, c = 0; m.nodes.forEach((n) => { if (n.A > 2) { s += Math.abs(n.bed - bed0.get(n.id)); c++; } }); console.log('year', y + 1, 'mean |change from start| (over 2 km2):', (s / c).toFixed(2), 'm;', ((Date.now() - t0) / 1000).toFixed(0), 's'); }
}
const bed = {}; let big = 0;
m.nodes.forEach((n) => { const dz = n.bed - bed0.get(n.id); bed[keyOf(n)] = +dz.toFixed(3); if (Math.abs(dz) > 3) big++; });
fs.writeFileSync(path.join(__dirname, '..', 'src', 'river-calib.js'),
  '/* Generated by tools/river-calibrate.js: how far each node\'s bed moves to a settled long profile. Do not edit by hand. */\n' +
  'window.Creek = window.Creek || {}; Creek.River = Creek.River || {}; Creek.River.CALIB = ' + JSON.stringify({ seed: 11, nodes: valley.nodes.length, bed }) + ';\n');
console.log('wrote src/river-calib.js; nodes moved more than 3 m:', big);
// check: a fresh natural model with the settled profile should now hold still
R.CALIB = { bed };
for (const seed of [31, 77]) {
  const c = new R.Model(valley, { seed, natural: true, params: { bedOnly: true } });
  const b0 = new Map(c.nodes.map((n) => [n.id, n.bed])); c.runYears(40);
  let s = 0, k = 0, w = 0; c.nodes.forEach((n) => { const d = Math.abs(n.bed - b0.get(n.id)); if (n.A > 2) { s += d; k++; w = Math.max(w, d); } });
  console.log('check seed', seed, ': mean |bed change| over 40 yr (over 2 km2):', (s / k).toFixed(2), 'm, worst', w.toFixed(2));
}
